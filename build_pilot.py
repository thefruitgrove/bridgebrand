def _measured_cnt(dims):
    return sum(1 for v in dims.values() if v is not None)

def _gate(pilot):
    """B규칙: 채워진 축이 2개 미만이면 공개하지 않는다(None 반환 → N/R 분기)."""
    if not pilot:
        return None
    if _measured_cnt(pilot.get("dims", {})) < 2:
        return None
    return pilot

def _is_verified_R(pilot):
    """R=100이 '탐색 후 무사건'(verified-default)인지 판정."""
    dims = pilot.get("dims", {})
    if dims.get("R") != 100:
        return False
    notes = " ".join(pilot.get("formula_notes", []))
    return ("확인된 논란 사건 없음" in notes) or ("탐색 후 무사건" in notes)

def _measure_kind(pilot):
    """공개 대상을 'measured'(순수 실측) / 'partial'(실측+R안전값)로 분류."""
    dims = pilot.get("dims", {})
    filled = [k for k, v in dims.items() if v is not None]
    vR = _is_verified_R(pilot)
    measured_axes = [k for k in filled if not (k == "R" and vR)]
    if vR and measured_axes:
        return "partial"
    return "measured"

def _method_tag(pilot):
    """대상명 옆 배지 텍스트를 판정에 따라 반환."""
    kind = _measure_kind(pilot)
    base = "비변동성 실측" if pilot.get("method") == "비변동성" else "실측 파일럿"
    if kind == "partial":
        return '<span class="realpilot-tag partial-tag" title="일부 축은 실측, R(반응)축은 \'탐색 후 무사건\'으로 부여된 잠정 기준선입니다.">부분 실측</span>'
    return f'<span class="realpilot-tag">{base}</span>'

