def r_axis_score(incidents, positive_events=None):
    """
    incidents: list of dicts {severity: '경미'|'중대'|'심각'|'초대형', attribution: 'A'|'B'|'C'|'D'|'F',
                               decay: 0~1 (시간가중치, 미리 계산해 전달)}
    positive_events: list of dicts {tier: '우수'|'최우수'|'역대급', decay: 0~1} (선택, 2026-09 신설)
    반환: R(반응) = 100 - min(100, max(0, 논란점수 - 긍정점수))
    """
    penalty = sum(
        SEVERITY_SCORES[i["severity"]] * ATTRIBUTION_COEFFICIENTS[i["attribution"]] * i["decay"]
        for i in incidents
    )
    bonus = sum(POSITIVE_SCORES[p["tier"]] * p["decay"] for p in (positive_events or []))
    net_penalty = max(0, penalty - bonus)
    return round(100 - min(100, net_penalty), 1)

